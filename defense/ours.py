# High-efficiency vector database
import faiss

class EmbeddingDefenseConfig(BaseDefenderConfig):
    """Embedding similarity-based defense mechanism configuration"""
    def __init__(self, model_path: str = os.environ.get("EMBEDDING_MODEL_PATH", "./checkpoints/best_model.pth"), 
                 similarity_threshold: float = 0.4, device: str = "cuda"):
        super().__init__()
        self.defender_name = "EmbeddingDefense"
        self.model_path = model_path
        self.similarity_threshold = similarity_threshold
        self.device = device

        self.base_defender = None

class EmbeddingDefense():
    """Embedding similarity-based defense mechanism"""

    def __init__(self, config: EmbeddingDefenseConfig):
        """
        Initialize the defense system
        
        Args:
            model_path: Fine-tuned embedding model path
            similarity_threshold: Similarity threshold, queries above this value will be rejected
            device: Runtime device
        """
        self.config = config
        self.similarity_threshold = config.similarity_threshold
        self.device = config.device

        self.base_defender = config.base_defender
        self.target_model = None


        # Load fine-tuned embedding model
        print(f"Loading embedding model: {config.model_path}")
        # pretrained_path = os.environ.get("MPNET_MODEL_PATH", "sentence-transformers/all-mpnet-base-v2")
        
        pretrained_path = os.environ.get("MPNET_MODEL_PATH", "sentence-transformers/all-mpnet-base-v2")
        self.tokenizer = AutoTokenizer.from_pretrained(pretrained_path)
        self.model = SentenceEncoderWithProjection()

        # Load fine-tuned weights
        if os.path.exists(config.model_path):
            state_dict = torch.load(config.model_path, map_location=config.device, weights_only=False)
            # Remove possible 'module.' prefix (generated by DataParallel)
            new_state_dict = {}
            for k, v in state_dict.items():
                if k.startswith('module.'):
                    new_state_dict[k[7:]] = v
                else:
                    new_state_dict[k] = v
            self.model.load_state_dict(new_state_dict["model_state_dict"])
            print("Fine-tuned weights loaded successfully")
        else:
            print(f"Warning: Fine-tuned weights file not found at {config.model_path}, using original model")

        self.model.to(config.device)
        self.model.eval()
        
        d = 256
        M = 32
        
        # For universal applicability, we use faiss-cpu directly
        self.index = faiss.IndexHNSWFlat(d, M, faiss.METRIC_INNER_PRODUCT)

        # HNSW parameters
        self.index.hnsw.efConstruction = 40
        self.index.hnsw.efSearch = 64

        print(f"HNSW index created (Metric=Inner Product / Cosine Similarity)")

        
        # Defense statistics
        self.defense_stats = {
            "total_queries": 0,
            "rejected_queries": 0,
            "first_queries": 0,
            "subsequent_queries": 0,
            "similarities_computed": 0
        }

        print(f"Defense system initialized, similarity threshold: {self.similarity_threshold}")

    def get_embedding(self, text: str) -> torch.Tensor:
        """Get text embedding vector"""
        with torch.no_grad():
            # Tokenize and move to device
            inputs = self.tokenizer(text, return_tensors='pt', 
                                   padding=True, truncation=True)
            inputs = {k: v.to(self.device) for k, v in inputs.items()}
            
            # Get model output
            embeddings = self.model(**inputs)

            return embeddings.squeeze()
        

    # Called after getting response for each attack round
    def set_embedding(self, query_list, response_list):
        print(f"Determining whether {len(query_list)} query prompts should be added to the database")
        gcgJudge = GCGJudge()
        gcg_scores = gcgJudge.score(query_list, response_list)

        is_mutil_attack = [score == 1 for score in gcg_scores]

        for i, s in enumerate(is_mutil_attack):
            if s == 1:
                query_embedding = self.get_embedding(query_list[i])
                query_embedding = query_embedding.unsqueeze(0) # shape [1,256]

                save_embedding = copy.deepcopy(query_embedding.cpu().numpy())
                faiss.normalize_L2(save_embedding)

                self.index.add(save_embedding)
                print(f"Current number of vectors in database: {self.index.ntotal}")

    def should_reject_query(self, query: str) -> Tuple[bool, float, str]:
        """
        Determine whether a query should be rejected
        
        Args:
            query: Current query
        Returns:
            (should_reject, similarity_score, reason)
        """
        self.defense_stats["total_queries"] += 1

        query_embedding = self.get_embedding(query).unsqueeze(0).cpu().numpy()
        faiss.normalize_L2(query_embedding)
        # D: Similarity (Scores), I: Index (Indices)
        D, I = self.index.search(query_embedding, 1)

        similarity = D.item()
        # print(type(similarity))
        if similarity > self.similarity_threshold:
            self.defense_stats["rejected_queries"] += 1
            return True, similarity, f"Similarity {similarity:.3f} > threshold {self.similarity_threshold}"
        else:
            return False, similarity, f"Similarity {similarity:.3f} <= threshold {self.similarity_threshold}"
        
    
    def get_defense_stats(self) -> Dict:
        """Get defense statistics"""
        stats = self.defense_stats.copy()
        if stats["total_queries"] > 0:
            stats["rejection_rate"] = stats["rejected_queries"] / stats["total_queries"]
        else:
            stats["rejection_rate"] = 0.0
        return stats
    
    def reset_defense_stats(self):
        self.defense_stats = {
            "total_queries": 0,
            "rejected_queries": 0,
            "first_queries": 0,
            "subsequent_queries": 0,
            "similarities_computed": 0
        }



    def get_response(self, adv_prompt_list: List[str]) -> List[str]:
        """
        Get response using our defender
        """

        # Initialize is_update
        is_update = [True] * len(adv_prompt_list)

        defense_decisions = []
        filtered_prompts = []
        filtered_indices = []

        reject_prompts = []

        if self.index.ntotal == 0:

            if self.base_defender:
                print(f"  🛡️ Using base defender to process {len(adv_prompt_list)} filtered queries")
                pass_response = self.base_defender.get_response(adv_prompt_list)
            else:
                print(f"  🛡️ Using original target model to process {len(adv_prompt_list)} filtered queries")
                pass_response = self.target_model.get_response(adv_prompt_list)

            response = pass_response

        else:
            for i, prompt in enumerate(adv_prompt_list):
                
                should_reject, similarity, reason = self.should_reject_query(
                    query=prompt
                )
                if should_reject:
                    is_update[i] = False
                
                defense_decision = {
                    "prompt_idx": i,
                    "prompt": prompt,
                    "should_reject": should_reject,
                    "similarity": similarity,
                    "reason": reason,
                }
                defense_decisions.append(defense_decision)
                
                if not should_reject:
                    filtered_prompts.append(prompt)
                    filtered_indices.append(i)
                else:
                    print(f"  🛡️ Defense rejected query {i}: {reason}")
                    reject_prompts.append(prompt)

            print(f"  Defense filtering: Original number of queries {len(adv_prompt_list)}")

            print(f"  -> {len(filtered_prompts)} queries passed")

            if len(filtered_prompts) == 0:
                # All queries rejected
                print("  Defense rejected all queries: Using preset response")
                return ["sorry, I can't assist with that." for i in range(len(adv_prompt_list))]
            else:
                # reject_response = ["sorry, I can't assist with that." for i in range(len(reject_prompts))]

                if self.base_defender:
                    print(f"  🛡️ Using base defender to process {len(filtered_prompts)} filtered queries")
                    pass_response = self.base_defender.get_response(filtered_prompts)
                else:
                    print(f"  🛡️ Using original target model to process {len(filtered_prompts)} filtered queries")
                    pass_response = self.target_model.get_response(filtered_prompts)

                response_dict = {}
                for idx, resp in zip(filtered_indices, pass_response):
                    response_dict[idx] = resp
                
                # Reassemble passed responses and rejected ones in original order
                response = []
                for i in range(len(adv_prompt_list)):
                    if i in filtered_indices:
                        response.append(response_dict[i])
                    else:
                        response.append("sorry, I can't assist with that.")


        # Maintain embedding database
        # Filter the response and prompts
        adv_prompt_list_filter = [data for data, mask in zip(adv_prompt_list, is_update) if mask]
        response_filter = [data for data, mask in zip(response, is_update) if mask]
        if len(adv_prompt_list_filter) != 0:
            self.set_embedding(adv_prompt_list_filter, response_filter)
    
        return response