    def get_response(self, prompts_list: List[str]) -> List[str]:
        """Batch-handle prompts_list and return responses in the original order.
        Uses batch inference for efficiency while keeping the same defense logic
        as get_response_per_sample.

        Args:
            prompts_list: List of user prompts.
            
        Returns:
            outputs_list: Response list in the original order.
        """
        # if self.use_target_as_infer and self.infer_model is None:
        #     self.infer_model = self.target_model

        # Use vicuna 13b as the inference model
        if self.infer_model is None:
            self.infer_model = load_infer_model_from_attack(self.attack_model, self.target_model.max_n_tokens)
        
        batchsize = len(prompts_list)
        print(f"\n[BT] BackTranslation batch defense start ({batchsize} queries)")
        

        passed_num = 0
        # Step 1: batch get initial responses from target model
        initial_responses = self.target_model.get_response(prompts_list)
        
        # Store final results, initialized to empty strings
        final_responses = [""] * batchsize
        
        # Step 2: check rejection phrases and collect samples needing further processing
        need_processing_indices = []
        need_processing_responses = []
        
        for i, response in enumerate(initial_responses):
            self.defense_stats["total_queries"] += 1
            
            if self._check_rejection(response, exclude_lack_of_info=False):
                self.defense_stats["defended_queries"] += 1
                self.defense_stats["rejected_by_phrase"] += 1
                final_responses[i] = self.reject_response
                print(f"  [BLOCK] Query {i}: rejected by phrase check")
            else:
                need_processing_indices.append(i)
                need_processing_responses.append(response)
        
        if not need_processing_indices:
            print("[STATS] All queries rejected by phrase check")
            return final_responses
        
        # Step 3: batch infer possible prompts
        print(f"[INFER] Inferring original prompts for {len(need_processing_indices)} responses...")
        inferred_prompts = self._infer_question_batch(need_processing_responses)

        # Step 4: batch evaluate likelihood
        need_regeneration_indices = []
        need_regeneration_prompts = []
        
        for idx, (original_idx, inferred_prompt, response) in enumerate(
            zip(need_processing_indices, inferred_prompts, need_processing_responses)
        ):
            is_reasonable, avg_log_likelihood, reason = self._filter_question_with_likelihood(
                inferred_prompt, response
            )
            
            # Update log-likelihood stats
            if avg_log_likelihood != 0.0:
                self.defense_stats["log_likelihoods"].append(avg_log_likelihood)
                self.defense_stats["max_log_likelihood"] = max(
                    self.defense_stats["max_log_likelihood"], 
                    avg_log_likelihood
                )
                self.defense_stats["min_log_likelihood"] = min(
                    self.defense_stats["min_log_likelihood"], 
                    avg_log_likelihood
                )
            
            if not is_reasonable:
                # Likelihood not reasonable, return original response
                print(f"  [PASS-ORIG] Query {original_idx}: failed likelihood check ({reason}) - returning original response")
                final_responses[original_idx] = response
                self.defense_stats["passed_queries"] += 1
                passed_num += 1
            else:
                # Likelihood reasonable, regenerate
                need_regeneration_indices.append(original_idx)
                need_regeneration_prompts.append(inferred_prompt)
        
        if not need_regeneration_indices:
            print("[STATS] No regeneration required")
            # Update average log-likelihood
            if self.defense_stats["log_likelihoods"]:
                self.defense_stats["avg_log_likelihood"] = sum(
                    self.defense_stats["log_likelihoods"]
                ) / len(self.defense_stats["log_likelihoods"])
            return final_responses
        
        # Step 5: batch regenerate responses
        print(f"[REGEN] Regenerating responses for {len(need_regeneration_indices)} inferred prompts...")
        new_responses = self.target_model.get_response(need_regeneration_prompts)
        
        # Step 6: check regenerated responses for rejection phrases
        for original_idx, new_response, original_response in zip(
            need_regeneration_indices, new_responses, 
            [initial_responses[idx] for idx in need_regeneration_indices]
        ):
            if not self._check_rejection(new_response):
                # New response is safe, return original response
                print(f"  [PASS] Query {original_idx}: defense passed - returning original response")
                final_responses[original_idx] = original_response
                self.defense_stats["passed_queries"] += 1
                passed_num += 1
            else:
                # New response has rejection phrase, block
                print(f"  [BLOCK] Query {original_idx}: rejected by likelihood filter")
                final_responses[original_idx] = self.reject_response
                self.defense_stats["defended_queries"] += 1
                self.defense_stats["rejected_by_likelihood"] += 1
        
        # Update average log-likelihood
        if self.defense_stats["log_likelihoods"]:
            self.defense_stats["avg_log_likelihood"] = sum(
                self.defense_stats["log_likelihoods"]
            ) / len(self.defense_stats["log_likelihoods"])
        
        print(f"\n[STATS] Batch defense result: {passed_num}/{batchsize} queries passed, "
              f"{batchsize - passed_num}/{batchsize} queries rejected")
        
        return final_responses

    def get_response_per_sample(self, prompt: str) -> str:
        """
        Get the response for a single prompt using back-translation.
        """
        self.defense_stats["total_queries"] += 1
        
        response = self.target_model.get_response([prompt])[0]

        if self._check_rejection(response, exclude_lack_of_info=False):
            self.defense_stats["defended_queries"] += 1
            self.defense_stats["rejected_by_phrase"] += 1
            print("[BLOCK] Query rejected by phrase check")
            return self.reject_response
        
        possible_prompt = self._infer_question(response)
        is_reasonable, avg_log_likelihood, reason = self._filter_question_with_likelihood(possible_prompt, response)

        # Update log-likelihood stats
        if avg_log_likelihood != 0.0:
            self.defense_stats["log_likelihoods"].append(avg_log_likelihood)
            self.defense_stats["max_log_likelihood"] = max(
                self.defense_stats["max_log_likelihood"], 
                avg_log_likelihood
            )
            self.defense_stats["min_log_likelihood"] = min(
                self.defense_stats["min_log_likelihood"], 
                avg_log_likelihood
            )

        if not is_reasonable:
            print(f"[PASS-ORIG] Query failed likelihood check: {reason}")
            print("Returning original response")
            self.defense_stats["passed_queries"] += 1
            return response
        
        new_response = self.target_model.get_response([possible_prompt])[0]

        if not self._check_rejection(new_response):
            print("[PASS] Query passed defense")
            self.defense_stats["passed_queries"] += 1
            return response

        print("[BLOCK] Query rejected by likelihood filter")
        self.defense_stats["defended_queries"] += 1
        self.defense_stats["rejected_by_likelihood"] += 1
        return self.reject_response


