    def _filter_question_with_likelihood(self, prompt: str, response: str) -> Tuple[bool, float, str]:
        """
        Filter the inferred prompt based on its likelihood to prevent harmful content.

        :param prompt: Inferred prompt to evaluate.
        :param response: Original response given by the assistant.
        :return: Boolean indicating whether the prompt is reasonable.
                float: The average log likelihood of the prompt.
                str: The reason for decision.
        """
        if self.threshold > -math.inf:

            conv = common.conv_template(self.infer_model.template)
            conv.append_message(conv.roles[0], prompt)
            conv.append_message(conv.roles[1], response)

            # print("translated back output:")
            log_likelihood = get_log_likelihood(conv, self.infer_model.model)
            print("Evaluating sample likelihood")
            print(f"avg logprobs: {sum(log_likelihood) / len(log_likelihood)} ")

            if sum(log_likelihood) / len(log_likelihood) > self.threshold:
                return True, sum(log_likelihood) / len(log_likelihood), f"Log likelihood {sum(log_likelihood) / len(log_likelihood)} is above threshold {self.threshold}"
            else:
                return False, sum(log_likelihood) / len(log_likelihood), f"Log likelihood {sum(log_likelihood) / len(log_likelihood)} is below threshold {self.threshold}"
        else:
            return True, 0.0, "No threshold set"

