    def get_defense_stats(self) -> Dict:
        """Get defense statistics"""
        stats = self.defense_stats.copy()
        
        # Calculate defense rates
        if stats["total_queries"] > 0:
            stats["defense_rate"] = stats["defended_queries"] / stats["total_queries"]
            stats["pass_rate"] = stats["passed_queries"] / stats["total_queries"]
            stats["rejected_by_phrase_rate"] = stats["rejected_by_phrase"] / stats["total_queries"]
            stats["rejected_by_likelihood_rate"] = stats["rejected_by_likelihood"] / stats["total_queries"]
        else:
            stats["defense_rate"] = 0.0
            stats["pass_rate"] = 0.0
            stats["rejected_by_phrase_rate"] = 0.0
            stats["rejected_by_likelihood_rate"] = 0.0
        
        # Calculate average log-likelihood
        if stats["log_likelihoods"]:
            stats["avg_log_likelihood"] = sum(stats["log_likelihoods"]) / len(stats["log_likelihoods"])
        
        # Remove detailed log-likelihood list (too long)
        stats["log_likelihood_count"] = len(stats["log_likelihoods"])
        del stats["log_likelihoods"]
        
        return stats
    
    def reset_stats(self):
        """Reset defense statistics"""
        self.defense_stats = {
            "total_queries": 0,
            "defended_queries": 0,
            "passed_queries": 0,
            "rejected_by_phrase": 0,
            "rejected_by_likelihood": 0,
            "avg_log_likelihood": 0.0,
            "max_log_likelihood": -float('inf'),
            "min_log_likelihood": float('inf'),
            "log_likelihoods": []
        }
        print("Defense statistics reset")
